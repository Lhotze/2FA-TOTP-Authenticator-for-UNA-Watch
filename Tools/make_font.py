#!/usr/bin/env python3
"""Makes gui/src/bb/Font.cpp from the X11 'Misc Fixed' bitmap fonts (public domain) in the sizes 5x8, 6x12, 7x14 and 10x20, characters 32 .. 255 (ISO 8859-1)."""
import gzip, os
from PIL import PcfFontFile

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', 'Software', 'Apps', 'TouchGFX-GUI', 'gui', 'src', 'ta', 'Font.cpp')
FONTS = [('5x8', 5, 8), ('6x12', 6, 12), ('7x14', 7, 14), ('10x20', 10, 20)]

lines = ['// Generated by Tools/make_font.py from the X11 "Misc Fixed" fonts (public domain) - do not edit.',
         '#include <ta/Font.hpp>', '', 'namespace ta {', '']
for name, w, h in FONTS:
    bpr = 1 if w <= 8 else 2
    f = PcfFontFile.PcfFontFile(gzip.open('/usr/share/fonts/misc/%s-ISO8859-1.pcf.gz' % name))
    lines.append('// %s: one byte per row (two, high byte first, when wider than 8), the highest bit is the leftmost pixel; characters 32 .. 255' % name)
    lines.append('static const uint8_t kData%s[] = {' % name)
    for code in range(32, 256):
        g = f.glyph[code]
        if g is None:
            rows = [0] * h
        else:
            im = g[3].convert('1')
            assert im.size == (w, h), (name, code, im.size)
            rows = []
            for y in range(h):
                b = 0
                for x in range(w):
                    if im.getpixel((x, y)):
                        b |= (0x8000 >> x) if bpr == 2 else (0x80 >> x)
                rows.append(b)
        data = [v for r in rows for v in (r >> 8, r & 255)] if bpr == 2 else rows
        lines.append('    ' + ', '.join('0x%02X' % r for r in data) + ',  // %d' % code)
    lines.append('};')
    lines.append('')
lines.append('const BitFont kFonts[kFontCount] = {')
for name, w, h in FONTS:
    lines.append('    { %d, %d, %d, kData%s },' % (w, h, 1 if w <= 8 else 2, name))
lines.append('};')
lines.append('')
lines.append('} // namespace ta')
open(out, 'w').write('\n'.join(lines) + '\n')
print('written', out)
